import fs from 'node:fs'
import path from 'node:path'
import solc from 'solc'
import { keccak256, toHex } from 'viem'

const here = import.meta.dirname
const vendorRoot = path.join(here, 'vendor')
const outRoot = path.join(here, 'out')
const coreAbiPath = path.join(here, '..', '..', 'packages', 'core', 'src', 'abis', 'launchpad.ts')
const coreTokenPath = path.join(here, '..', '..', 'packages', 'core', 'src', 'abis', 'ascend-token.ts')

const verification = JSON.parse(fs.readFileSync(path.join(here, 'verification.json'), 'utf8'))

const sourcePaths = []
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.name.endsWith('.sol')) {
      sourcePaths.push(path.relative(vendorRoot, full).split(path.sep).join('/'))
    }
  }
}
walk(vendorRoot)
sourcePaths.sort()

if (sourcePaths.length !== verification.sources.length) {
  console.error(
    `vendor has ${sourcePaths.length} sources, verification.json lists ${verification.sources.length}`
  )
  process.exit(1)
}

const sources = {}
for (const p of sourcePaths) sources[p] = { content: fs.readFileSync(path.join(vendorRoot, p), 'utf8') }

const input = {
  language: 'Solidity',
  sources,
  settings: {
    ...verification.compilerSettings,
    outputSelection: {
      '*': {
        '*': [
          'abi',
          'evm.bytecode.object',
          'evm.deployedBytecode.object',
          'evm.deployedBytecode.immutableReferences',
          'evm.methodIdentifiers'
        ]
      }
    }
  }
}

console.log(`compiling ${sourcePaths.length} sources with solc ${solc.version()} ...`)
const started = Date.now()
const output = JSON.parse(solc.compile(JSON.stringify(input)))
console.log(`compiled in ${((Date.now() - started) / 1000).toFixed(1)}s`)

const errors = (output.errors ?? []).filter((e) => e.severity === 'error')
const warnings = (output.errors ?? []).filter((e) => e.severity === 'warning')
for (const w of warnings) console.warn(`warning: ${w.formattedMessage?.split('\n')[0] ?? w.message}`)
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage ?? e.message)
  process.exit(1)
}

fs.rmSync(outRoot, { recursive: true, force: true })
fs.mkdirSync(path.join(outRoot, 'artifacts'), { recursive: true })

let artifactCount = 0
const srcContracts = []
for (const [sourceName, fileOut] of Object.entries(output.contracts)) {
  for (const [contractName, contract] of Object.entries(fileOut)) {
    const artifact = {
      contractName,
      sourceName,
      abi: contract.abi,
      bytecode: '0x' + (contract.evm?.bytecode?.object ?? ''),
      deployedBytecode: '0x' + (contract.evm?.deployedBytecode?.object ?? ''),
      immutableReferences: contract.evm?.deployedBytecode?.immutableReferences ?? {},
      methodIdentifiers: contract.evm?.methodIdentifiers ?? {}
    }
    fs.writeFileSync(
      path.join(outRoot, 'artifacts', `${contractName}.json`),
      JSON.stringify(artifact, null, 2) + '\n'
    )
    artifactCount++
    if (sourceName.startsWith('src/')) srcContracts.push(contractName)
  }
}
srcContracts.sort()
console.log(`artifacts written: ${artifactCount} (src contracts: ${srcContracts.join(', ')})`)

const launchpad = JSON.parse(fs.readFileSync(path.join(outRoot, 'artifacts', 'AscendLaunchpad.json'), 'utf8'))

const eventTopics = {}
for (const item of launchpad.abi) {
  if (item.type !== 'event') continue
  const signature = `${item.name}(${item.inputs.map((i) => i.type).join(',')})`
  eventTopics[item.name] = keccak256(toHex(signature))
}

const generated = `// AUTO-GENERATED by tools/abi-extract/extract.js — do not edit by hand.
// AscendLaunchpad at ${verification.address} (Elysium testnet 99801), compiled from the
// verified sources with solc ${verification.compilerVersion} (viaIR, optimizer 200 runs,
// evmVersion cancun, bytecodeHash none). See tools/abi-extract/verification.json.

export const launchpadAbi = ${JSON.stringify(launchpad.abi, null, 2)} as const

export const launchpadEventTopics = ${JSON.stringify(eventTopics, null, 2)} as const
`
fs.writeFileSync(coreAbiPath, generated)
console.log(`generated ${coreAbiPath}`)
console.log(`event topics: ${Object.keys(eventTopics).join(', ')}`)

const token = JSON.parse(fs.readFileSync(path.join(outRoot, 'artifacts', 'AscendToken.json'), 'utf8'))
const generatedToken = `// AUTO-GENERATED by tools/abi-extract/extract.js — do not edit by hand.
// AscendToken, compiled from the verified sources with solc ${verification.compilerVersion}
// (viaIR, optimizer 200 runs, evmVersion cancun, bytecodeHash none).
// See tools/abi-extract/verification.json.

export const tokenAbi = ${JSON.stringify(token.abi, null, 2)} as const

export const tokenCreationBytecode =
  '${token.bytecode}' as const
`
fs.writeFileSync(coreTokenPath, generatedToken)
console.log(`generated ${coreTokenPath} (creation bytecode ${(token.bytecode.length - 2) / 2} bytes)`)
